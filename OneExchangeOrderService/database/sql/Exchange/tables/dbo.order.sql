CREATE TABLE [exch_order].[order] (
    [_id] UNIQUEIDENTIFIER DEFAULT newId() NOT NULL,
    [_clustRowId] BIGINT IDENTITY(1, 1) NOT NULL,
    [_insertedDateTime] DATETIMEOFFSET DEFAULT getdate() NOT NULL,
    [_insertedBy] NVARCHAR(50) NOT NULL,
    [_updatedDateTime] DATETIMEOFFSET,
    [_updatedBy] NVARCHAR(50),
    [_status] BIT DEFAULT 1 NOT NULL,
    [_statusReason] NVARCHAR(100),
    [tenantId] UNIQUEIDENTIFIER NOT NULL,
    [tradingAgreementId] UNIQUEIDENTIFIER NOT NULL,
    [orderType] NVARCHAR(30) NOT NULL, -- "BOOKING"
    [orderNumber] NVARCHAR(50) NOT NULL, -- Autogenerated 
    [orderStatus] NVARCHAR(20) NOT NULL, -- "PENDING", "CONFIRMED", "CANCELLED", "FAILED"
    [externalSourceSystem] NVARCHAR(50), -- Supplier Partner Code
    [externalReferenceId] NVARCHAR(50), -- The order confirmation number provided by the Supplier Partner (e.g. GP provides confirmation number for alloted units as part of inventory, Choice provides this once we call Choice API to book)
    [orderDate] DATETIME,
    [salesPersonEmail] NVARCHAR(255), -- Email address of the sales person
    [salesPersonFirstName] NVARCHAR(255), -- Full name of the sales person, to be displayed in reservation details
    [salesPersonLastName] NVARCHAR(255), -- Full name of the sales person, to be displayed in reservation details

    [billToProfileId] UNIQUEIDENTIFIER, -- Billing address profile

    -- Change on Jul 3, removed User table    
    [customerExternalSourceSystem] NVARCHAR(50), -- External system the customer comes from (e.g. BGO)
    [customerExternalReferenceId] NVARCHAR(50), -- Customer's Id in the external system (e.g. BGO Owner Id)
	[customerFirstName] NVARCHAR(255), -- First name of the customer, to be displayed in reservation details
    [customerLastName] NVARCHAR(255), -- Last name of the customer, to be displayed in reservation details
    [customerPhoneNumber] NVARCHAR(30), -- Capture phone number at the time of the order, in case it changes after
    [customerEmailAddress] NVARCHAR(50), -- Capture email address at the time of the order, in case it changes after
    [customerMemberLevel] NVARCHAR(50), -- Capture member's tier level "e.g. PREMIER Gold" at the time of the order, this is mainly for reporting 

    [cancelDate] DATETIME, -- Set if the order is cancelled
    [currency] NVARCHAR(10) NOT NULL, -- Currency can be a FIAT currenct like USD, EUR or a partner point currenty like CHOP, or BGVP etc. 
    [subtotal] DECIMAL(19,4), -- for MVP this is the points in BG points (BGVP)
    [taxCurrency] NVARCHAR(10) NOT NULL, -- Currency can be a FIAT currenct like USD, EUR or a partner point currenty like CHOP, or BGVP etc.     
    [taxAmount] DECIMAL(19,4), -- always 0 for MVP.
    [feeCurrency] NVARCHAR(10) NOT NULL, -- Currency can be a FIAT currenct like USD, EUR or a partner point currenty like CHOP, or BGVP etc. 
    [orderFee] DECIMAL(19,4) NOT NULL, -- Booking fee based on inRule
    [waiveFee] BIT DEFAULT 0 NOT NULL, -- Whether the sales person waived the fee or not
    [memo] NVARCHAR(500),
    [extendedReference] NVARCHAR(2000),
    [ValidFrom] DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL
    CONSTRAINT DF_order_ValidFrom DEFAULT SYSUTCDATETIME(),
    [ValidTo] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL
    CONSTRAINT DF_order_ValidTo DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
    PERIOD FOR SYSTEM_TIME (ValidFrom, ValidTo),

    CONSTRAINT [pk_order] PRIMARY KEY NONCLUSTERED ([_id]),
    CONSTRAINT [ck_orderType] CHECK (orderType = 'BOOKING'),
    CONSTRAINT [ck_orderStatus] CHECK (orderStatus in ('PENDING', 'PENDING_CANCELLATION', 'FAILED', 'CONFIRMED', 'CANCELLED')),
    CONSTRAINT [uk_order_number] UNIQUE ([tenantId], [orderNumber]),
    CONSTRAINT [ck_order_extendedReference] CHECK (ISJSON(extendedReference) = 1)
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = [exch_order].[order_history]));
GO
CREATE CLUSTERED INDEX [ix_order_clustRowId] ON [exch_order].[order] ([_clustRowId])
GO
CREATE NONCLUSTERED INDEX [ix_order_tenantId] ON [exch_order].[order] ([tenantId])
GO
CREATE NONCLUSTERED INDEX [ix_order_customerExternalReferenceId] ON [exch_order].[order] ([customerExternalReferenceId])
GO
CREATE NONCLUSTERED INDEX [ix_order_orderNumber] ON [exch_order].[order] ([orderNumber])
GO
CREATE NONCLUSTERED INDEX [ix_order_orderStatus] ON [exch_order].[order] ([orderStatus])
GO
CREATE NONCLUSTERED INDEX [ix_order_externalReferenceId] ON [exch_order].[order] ([externalReferenceId])