-- Named "Return" to cover future scenarios, for MVP this means "Order Cancellation"
CREATE TABLE [exch_order].[orderReturn] (
    [_id] UNIQUEIDENTIFIER DEFAULT newId() NOT NULL,
    [_clustRowId] BIGINT IDENTITY(1, 1) NOT NULL,
    [_insertedDateTime] DATETIMEOFFSET DEFAULT getdate() NOT NULL,
    [_insertedBy] NVARCHAR(50) NOT NULL,
    [_updatedDateTime] DATETIMEOFFSET,
    [_updatedBy] NVARCHAR(50),
    [_status] BIT DEFAULT 1 NOT NULL,
    [_statusReason] NVARCHAR(100),
    [tenantId] UNIQUEIDENTIFIER NOT NULL,    
    [orderId] UNIQUEIDENTIFIER NOT NULL,
    [returnNumber] NVARCHAR(50) NOT NULL, -- Autogenerated - Cancellation number
    [returnDate] DATETIME NOT NULL, -- Cancel Date

    [salesPersonEmail] NVARCHAR(255), -- Email address of the sales person
    [salesPersonFirstName] NVARCHAR(255), -- Full name of the sales person, to be displayed in reservation details
    [salesPersonLastName] NVARCHAR(255), -- Full name of the sales person, to be displayed in reservation details

    [externalSourceSystem] NVARCHAR(50), -- External system the order is cancelled in (e.g. CHO)
    [externalReferenceId] NVARCHAR(50), -- Cancellation Id in the external system

    [returnFeeCurrency] NVARCHAR(10), -- Cancellation Fee currency
    [returnFeeAmount] DECIMAL(19,4), -- Cancellation Fee 
    [waiveFee] BIT DEFAULT 0 NOT NULL, -- Whether the sales person waived the fee or not
    [memo] NVARCHAR(500),
    CONSTRAINT [pk_orderReturn] PRIMARY KEY NONCLUSTERED ([_id]),
    CONSTRAINT [uk_orderReturn_orderId] UNIQUE ([orderId]),
    CONSTRAINT [fk_orderReturn_order] FOREIGN KEY ([orderId]) 
        REFERENCES [exch_order].[order] ([_id])
)
GO
CREATE CLUSTERED INDEX [ix_orderReturn_clustRowId] ON [exch_order].[orderReturn] ([_clustRowId])
GO
CREATE NONCLUSTERED INDEX [ix_orderReturn_externalReferenceId] ON [exch_order].[orderReturn] ([externalReferenceId])